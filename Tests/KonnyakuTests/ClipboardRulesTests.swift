import AppKit
import XCTest
@testable import Konnyaku

final class ClipboardRulesTests: XCTestCase {
    private let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private func isNewCopy(
        changeCount: Int = 5,
        seenChangeCount: Int = 4,
        ownCopyChangeCount: Int = -1,
        types: [NSPasteboard.PasteboardType] = [.string]
    ) -> Bool {
        ClipboardRules.isNewCopy(
            changeCount: changeCount,
            seenChangeCount: seenChangeCount,
            ownCopyChangeCount: ownCopyChangeCount,
            types: types
        )
    }

    private func isNewRequest(
        _ text: String?,
        sourceText: String = "Hello",
        output: String = "こんにちは",
        lastRunFailed: Bool = false
    ) -> Bool {
        ClipboardRules.isNewRequest(
            text,
            sourceText: sourceText,
            output: output,
            lastRunFailed: lastRunFailed
        )
    }

    // MARK: - Change count

    func testChangedCountIsNewCopy() {
        XCTAssertTrue(isNewCopy())
    }

    func testFirstPressReadsTheClipboard() {
        // The controller starts with -1, which no real change count matches.
        XCTAssertTrue(isNewCopy(changeCount: 0, seenChangeCount: -1))
    }

    func testUnchangedCountIsNotNew() {
        XCTAssertFalse(isNewCopy(changeCount: 5, seenChangeCount: 5))
    }

    func testOwnCopyIsNotNew() {
        XCTAssertFalse(isNewCopy(changeCount: 5, ownCopyChangeCount: 5))
    }

    func testEarlierOwnCopyDoesNotHideALaterCopy() {
        XCTAssertTrue(isNewCopy(changeCount: 6, ownCopyChangeCount: 5))
    }

    // MARK: - Concealed types

    func testConcealedTransientAndGeneratedTypesAreNotNew() {
        XCTAssertFalse(isNewCopy(types: [.string, concealed]))
        XCTAssertFalse(isNewCopy(types: [.string, transient]))
        XCTAssertFalse(isNewCopy(types: [.string, generated]))
    }

    func testNoTypesIsStillNewCopy() {
        // Blank or missing text is ruled out later, by isNewRequest.
        XCTAssertTrue(isNewCopy(types: []))
    }

    // MARK: - Text

    func testPlainNewTextIsNewRequest() {
        XCTAssertTrue(isNewRequest("Good morning"))
    }

    func testNilOrBlankTextIsNotNewRequest() {
        XCTAssertFalse(isNewRequest(nil))
        XCTAssertFalse(isNewRequest(""))
        XCTAssertFalse(isNewRequest("  \n\t "))
    }

    func testBlankTextIsNotNewRequestEvenWithBlankSourceAndOutput() {
        XCTAssertFalse(isNewRequest(" ", sourceText: "", output: ""))
    }

    func testNewTextWithEmptySourceAndOutputIsNewRequest() {
        XCTAssertTrue(isNewRequest("Hello", sourceText: "", output: ""))
    }

    func testOwnSourceIsNotNewRequest() {
        XCTAssertFalse(isNewRequest("Hello"))
    }

    func testOwnOutputIsNotNewRequest() {
        XCTAssertFalse(isNewRequest("こんにちは"))
    }

    func testOwnTextMatchesIgnoringSurroundingWhitespace() {
        XCTAssertFalse(isNewRequest("  Hello\n"))
        XCTAssertFalse(isNewRequest("\tこんにちは  "))
        XCTAssertFalse(isNewRequest("Hello", sourceText: "\n Hello \n"))
        XCTAssertFalse(isNewRequest("こんにちは", output: "こんにちは\n"))
    }

    func testInnerWhitespaceAndCaseStillMakeNewText() {
        XCTAssertTrue(isNewRequest("Hel lo"))
        XCTAssertTrue(isNewRequest("hello"))
    }

    // MARK: - Retry

    func testSourceAfterFailedRunIsRetry() {
        XCTAssertTrue(isNewRequest("Hello", lastRunFailed: true))
        XCTAssertTrue(isNewRequest(" Hello ", lastRunFailed: true))
    }

    func testOutputAfterFailedRunIsStillOwnText() {
        XCTAssertFalse(isNewRequest("こんにちは", lastRunFailed: true))
    }

    // MARK: - Selection fallback

    func testRestoredClipboardStaysSeenIfItWasSeenBeforeTheCopy() {
        let seen = ClipboardRules.seenChangeCount(
            4,
            countBeforeCopy: 4,
            restoredChangeCount: 6
        )
        XCTAssertEqual(seen, 6)
    }

    func testRestoredClipboardStaysNewIfItWasNewBeforeTheCopy() {
        let seen = ClipboardRules.seenChangeCount(
            3,
            countBeforeCopy: 4,
            restoredChangeCount: 6
        )
        XCTAssertEqual(seen, 3)
    }

    func testSeenCountKeptWhenNothingWasRestored() {
        let notRestored = ClipboardRules.seenChangeCount(
            4,
            countBeforeCopy: 4,
            restoredChangeCount: nil
        )
        XCTAssertEqual(notRestored, 4)
        let noCopy = ClipboardRules.seenChangeCount(
            4,
            countBeforeCopy: nil,
            restoredChangeCount: nil
        )
        XCTAssertEqual(noCopy, 4)
    }

    // MARK: - Trimming

    func testTrimmedDropsSurroundingWhitespaceOnly() {
        XCTAssertEqual(ClipboardRules.trimmed("  a b \n"), "a b")
        XCTAssertNil(ClipboardRules.trimmed(" \n"))
        XCTAssertNil(ClipboardRules.trimmed(nil))
    }
}
